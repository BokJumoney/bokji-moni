import re


def preprocess_markdown(markdown: str):
    """
    HWPX -> Markdown 결과를
    LLM 구조화 전에 최소한으로 정리한다.
    """

    # -------------------------------------------------
    # 1. 줄 끝 공백 제거
    # -------------------------------------------------
    markdown = "\n".join(
        line.rstrip()
        for line in markdown.splitlines()
    )


    # -------------------------------------------------
    # 2. 빈 줄 정리
    # -------------------------------------------------
    markdown = re.sub(
        r"\n{3,}",
        "\n\n",
        markdown
    )


    # -------------------------------------------------
    # 3. 서식 번호 분리
    # 예:
    # 서식 1 신청서
    #
    # ->
    # 서식 1
    #
    # 신청서
    # -------------------------------------------------
    markdown = re.sub(
        r"(서식\s*\d+)\s+",
        r"\1\n\n",
        markdown
    )


    # -------------------------------------------------
    # 4. 면 표시 분리
    # 예:
    # [1 면]
    # -------------------------------------------------
    markdown = re.sub(
        r"(\[\d+\s*면\])",
        r"\n\n\1\n\n",
        markdown
    )


    # -------------------------------------------------
    # 5. TABLE 태그 주변 정리
    # -------------------------------------------------
    markdown = re.sub(
        r"\[TABLE\]",
        "\n[TABLE]\n",
        markdown
    )

    markdown = re.sub(
        r"\[/TABLE\]",
        "\n[/TABLE]\n",
        markdown
    )


    # -------------------------------------------------
    # 6. 체크박스 앞 줄바꿈
    # -------------------------------------------------
    markdown = re.sub(
        r"\s*(□)",
        r"\n\1",
        markdown
    )


    # -------------------------------------------------
    # 7. 동그라미 항목 앞 줄바꿈
    # -------------------------------------------------
    markdown = re.sub(
        r"\s*(○)",
        r"\n\1",
        markdown
    )


    # -------------------------------------------------
    # 8. 연속 공백 제거
    # -------------------------------------------------
    markdown = re.sub(
        r"[ \t]{2,}",
        " ",
        markdown
    )


    # -------------------------------------------------
    # 9. 빈 줄 최종 정리
    # -------------------------------------------------
    markdown = re.sub(
        r"\n{3,}",
        "\n\n",
        markdown
    )


    return markdown.strip()